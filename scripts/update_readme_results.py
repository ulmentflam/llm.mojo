#!/usr/bin/env python3
"""Regenerate the README's precision-comparison table from the arm fragments.

Rewrites only the region between two HTML-comment markers in README.md, from
whichever docs/ai/v2_arm_results/*.json files exist. Run after each arm
finishes; it is idempotent and safe to run with only some arms present.

Why generated rather than hand-edited: the previous table was written by hand
and stood for days asserting a precision comparison that the runs behind it did
not support. A table assembled from the runs' own artifacts cannot say
something the runs did not measure, and it states plainly which arms are
missing instead of quietly showing five rows as if they were six.
"""

import json
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
RESULTS_DIR = REPO_ROOT / "docs" / "ai" / "v2_arm_results"
README = REPO_ROOT / "README.md"

BEGIN = (
    "<!-- BEGIN v2-precision-table (generated by scripts/update_readme_results.py) -->"
)
END = "<!-- END v2-precision-table -->"

ORDER = [
    ("124M", "bf16"),
    ("124M", "fp8"),
    ("124M", "nvfp4"),
    ("774M", "bf16"),
    ("774M", "fp8"),
    ("774M", "nvfp4"),
]


def load_arms() -> dict[str, dict]:
    if not RESULTS_DIR.is_dir():
        return {}
    out = {}
    for p in sorted(RESULTS_DIR.glob("*.json")):
        r = json.loads(p.read_text())
        out[r["arm"]] = r
    return out


def render(arms: dict[str, dict]) -> str:
    lines = [
        BEGIN,
        "",
        "| Model | Precision | Final val loss | HellaSwag acc_norm | Tokens/s (this box) | Checkpoint |",
        "|---|---|---:|---|---:|---|",
    ]
    missing = []
    for scale, precision in ORDER:
        key = f"{scale}-{precision}"
        r = arms.get(key)
        if r is None:
            missing.append(key)
            lines.append(
                f"| GPT-2 {scale} | {precision} | _training_ | _training_ | _—_ | _pending_ |"
            )
            continue
        acc = 100 * r["hellaswag_acc"]
        repo = r["hf_repo"]
        name = repo.split("/", 1)[1]
        lines.append(
            f"| GPT-2 {scale} | {precision} | {r['final_val_loss']:.4f} | "
            f"{acc:.2f}% ({r['hellaswag_k']}/{r['hellaswag_n']}) | "
            f"~{r['median_tok_per_s'] // 1000}k | "
            f"[{name}](https://huggingface.co/{repo}) |"
        )

    lines.append("")
    if missing:
        lines.append(
            f"> **{len(ORDER) - len(missing)} of {len(ORDER)} arms complete.** "
            f"Still training: {', '.join(missing)}. Rows fill in as each arm "
            "finishes, is scored, and is published."
        )
        lines.append("")

    lines.append(
        "Every row is generated by `scripts/update_readme_results.py` from "
        "`docs/ai/v2_arm_results/*.json`, which `scripts/record_arm_result.py` "
        "writes by parsing each run's own `train.log` and `make eval` output. "
        "Nothing in this table is entered by hand."
    )
    lines.append("")
    lines.append(END)
    return "\n".join(lines)


def main() -> int:
    text = README.read_text()
    if BEGIN not in text or END not in text:
        raise SystemExit(
            f"markers not found in {README}. Add:\n  {BEGIN}\n  {END}\n"
            "around the region this script should own."
        )
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)

    arms = load_arms()
    README.write_text(head + render(arms) + tail)
    print(
        f"[update_readme_results] {len(arms)}/{len(ORDER)} arms rendered into README.md"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
